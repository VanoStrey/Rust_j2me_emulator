pub const STYLE_PLAIN: i32 = 0;
pub const STYLE_BOLD: i32 = 1;
pub const STYLE_ITALIC: i32 = 2;
pub const STYLE_UNDERLINED: i32 = 4;

pub const SIZE_SMALL: i32 = 8;
pub const SIZE_MEDIUM: i32 = 0; // standard medium
pub const SIZE_LARGE: i32 = 16;

pub const FACE_SYSTEM: i32 = 0;
pub const FACE_MONOSPACE: i32 = 32;
pub const FACE_PROPORTIONAL: i32 = 64;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FontSpec {
    pub face: i32,
    pub style: i32,
    pub size: i32,
}

impl Default for FontSpec {
    fn default() -> Self {
        Self {
            face: FACE_SYSTEM,
            style: STYLE_PLAIN,
            size: SIZE_MEDIUM,
        }
    }
}

impl FontSpec {
    pub fn new(face: i32, style: i32, size: i32) -> Self {
        Self { face, style, size }
    }

    pub fn get_height(&self) -> i32 {
        match self.size {
            SIZE_SMALL => 9,
            SIZE_LARGE => 18,
            _ => 13, // SIZE_MEDIUM
        }
    }

    pub fn get_baseline_position(&self) -> i32 {
        match self.size {
            SIZE_SMALL => 7,
            SIZE_LARGE => 14,
            _ => 10,
        }
    }

    pub fn char_width(&self, _c: char) -> i32 {
        let base_w = match self.size {
            SIZE_SMALL => 6,
            SIZE_LARGE => 10,
            _ => 8,
        };
        if self.style & STYLE_BOLD != 0 {
            base_w + 1
        } else {
            base_w
        }
    }

    pub fn string_width(&self, s: &str) -> i32 {
        let w = self.char_width(' ');
        (s.chars().count() as i32) * w
    }

    pub fn substring_width(&self, s: &str, offset: usize, len: usize) -> i32 {
        let sub: String = s.chars().skip(offset).take(len).collect();
        self.string_width(&sub)
    }

    /// Rasterize string into RGBA buffer
    pub fn render_string(
        &self,
        pixels: &mut [u32],
        fb_w: i32,
        fb_h: i32,
        clip: (i32, i32, i32, i32),
        text: &str,
        mut x: i32,
        y: i32,
        color: u32,
    ) {
        let (cx, cy, cw, ch) = clip;
        let font_h = self.get_height();
        let char_w = self.char_width(' ');
        let is_bold = self.style & STYLE_BOLD != 0;
        let is_italic = self.style & STYLE_ITALIC != 0;
        let is_underline = self.style & STYLE_UNDERLINED != 0;

        for char_glyph in text.chars() {
            let glyph = get_glyph_8x8(char_glyph);
            for dy in 0..font_h {
                let py = y + dy;
                if py < cy || py >= cy + ch || py < 0 || py >= fb_h {
                    continue;
                }
                let src_row = ((dy * 8) / font_h).min(7) as usize;
                let bit_row = glyph[src_row];
                let italic_slant = if is_italic {
                    ((font_h - 1 - dy) * 2 / font_h).max(0)
                } else {
                    0
                };

                for dx in 0..char_w {
                    let src_col = ((dx * 8) / char_w).min(7) as usize;
                    if (bit_row & (1 << (7 - src_col))) != 0 {
                        let px = x + dx + italic_slant;
                        if px >= cx && px < cx + cw && px >= 0 && px < fb_w {
                            pixels[(py * fb_w + px) as usize] = color;
                            if is_bold && px + 1 < cx + cw && px + 1 < fb_w {
                                pixels[(py * fb_w + px + 1) as usize] = color;
                            }
                        }
                    }
                }
            }

            if is_underline {
                let py = y + self.get_baseline_position() + 1;
                if py >= cy && py < cy + ch && py >= 0 && py < fb_h {
                    for px in x..x + char_w {
                        if px >= cx && px < cx + cw && px >= 0 && px < fb_w {
                            pixels[(py * fb_w + px) as usize] = color;
                        }
                    }
                }
            }

            x += char_w;
        }
    }
}

